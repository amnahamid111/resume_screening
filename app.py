import streamlit as st

st.title("AI Resume Screening System")

skills_list = [
    "Python",
    "SQL",
    "Machine Learning",
    "TensorFlow",
    "PyTorch",
    "AWS",
    "Docker",
    "NLP",
    "Power BI",
    "Excel",
    "Customer Service",
    "Communication",
    "Microsoft Office",
    "Data Entry",
    "Problem Solving",
    "Team Coordination"
]

import fitz
def extract_text_from_pdf(uploaded_file):
  text=""

  pdf=fitz.open(
      stream=uploaded_file.read(),
      filetype='pdf'
  )
  for page in pdf:
    text+=page.get_text()

    # The return statement should be outside the loop to accumulate all text
  return text

  def extract_skills(text):
    found_skills=[]
    # skills_list is not defined yet, this will cause a NameError if called
    # For now, let's assume it will be defined or passed as an argument.
    for skill in skills_list:
      if skill.lower() in text.lower():
         found_skills.append(skill)
    return found_skills

uploaded_file = st.file_uploader(
    "Upload Resume (PDF)",
    type=["pdf"]
)

if uploaded_file:
    st.success("Resume uploaded successfully")

    resume_text=extract_text_from_pdf(uploaded_file)
    st.subheader('Extracted Resume Text')

    st.text_area(
      'Resume Content',
      resume_text,
      height=300
  )

    skills=extract_skills(resume_text)
  
    st.write("Skills Found:")
    st.write(skills)
