# Commented out IPython magic to ensure Python compatibility.
skill_score = (
    matched / len(required_skills)
) * 70

experience_score = min(
    experience * 5,
    20
)

education_score = 0

if education == "PhD":
    education_score = 10

elif education in ["M.Sc", "M.Tech"]:
    education_score = 8

elif education in ["B.Sc", "B.E"]:
    education_score = 5

final_score = int(
    skill_score +
    experience_score +
    education_score
)

final_score = min(
    final_score,
    100
)
job_skills = {

    "Data Scientist": [
        "Python",
        "SQL",
        "Machine Learning",
        "Power BI"
    ],

    "Software Engineer": [
        "Python",
        "SQL",
        "Docker"
    ],

    "AI Researcher": [
        "Python",
        "TensorFlow",
        "PyTorch",
        "NLP"
    ],

    "Customer Service Representative": [
        "Customer Service",
        "Communication",
        "Microsoft Office"
    ]
}

job_role = st.selectbox(
    "Select Job Role",
    list(job_skills.keys())
)

uploaded_file = st.file_uploader(
    "📄 Upload Resume (PDF)",
    type=["pdf"]
)

if uploaded_file:

    st.success("✅ Resume uploaded successfully")

    resume_text = extract_text_from_pdf(uploaded_file)

    skills = extract_skills(resume_text)

    experience = extract_experience(resume_text)

    education = extract_education(resume_text)

    required_skills = job_skills[job_role]

    matched = 0

    for skill in required_skills:

        if skill in skills:
            matched += 1

    skill_score = (
        matched / len(required_skills)
    ) * 70

    experience_score = min(
        experience * 5,
        20
    )

    education_score = 0

    if education == "PhD":
        education_score = 10

    elif education in ["M.Sc", "M.Tech"]:
        education_score = 8

    elif education in ["B.Sc", "B.E"]:
        education_score = 5

    final_score = int(
        skill_score +
        experience_score +
        education_score
    )

    final_score = min(
        final_score,
        100
    )

    match_percentage = int(
        (matched / len(required_skills)) * 100
    )

    col1, col2, col3, col4 = st.columns(4)

    with col1:
        st.metric(
            "📅 Experience",
            f"{experience} Years"
        )

    with col2:
        st.metric(
            "🎓 Education",
            education
        )

    with col3:
        st.metric(
            "🛠 Skills Found",
            len(skills)
        )

    with col4:
        st.metric(
            "🎯 Job Match",
            f"{final_score}%"
        )

    st.markdown("---")

    st.subheader("🛠 Skills Detected")

    skills_html = ""

    for skill in skills:
        skills_html += (
            f"<span class='skill-tag'>{skill}</span> "
        )

    st.markdown(
        skills_html,
        unsafe_allow_html=True
    )

    st.markdown("---")

    st.subheader("📋 Required Skills Match")

    for skill in required_skills:

        if skill in skills:
            st.success(f"✓ {skill}")
        else:
            st.error(f"✗ {skill}")

    st.subheader("📈 Match Summary")

    c1, c2, c3 = st.columns(3)

    with c1:
        st.metric(
            "Matched Skills",
            f"{matched}/{len(required_skills)}"
        )

    with c2:
        st.metric(
            "Skills Found",
            len(skills)
        )

    with c3:
        st.metric(
            "Skill Match %",
            f"{match_percentage}%"
        )

    st.markdown("---")

    st.subheader("📊 Candidate Evaluation")

    st.progress(final_score / 100)

    st.metric(
        "Final Candidate Score",
        f"{final_score}%"
    )

    if final_score >= 75:

        st.success(
            "✅ Recommended for Interview"
        )

    elif final_score >= 50:

        st.warning(
            "⚠ Potential Candidate"
        )

    else:

        st.error(
            "❌ Not Suitable For This Job"
        )

    st.markdown("---")

    with st.expander(
        "📄 View Extracted Resume Text"
    ):

        st.text_area(
            "Resume Content",
            resume_text,
            height=350
        )
